const char* Tr(StrId id) {
    if (id < 0 || id >= STR_COUNT)
        return "";
    const char* s = g_strings[g_currentLang][id].s;
    if (s)
        return s;
    // Repli sur LANG_FR si jamais la case courante est vide - ne devrait pas
    // arriver (tableau rempli integralement pour LANG_FR/LANG_EN ci-dessus)
    // mais evite un ImGui::Text(nullptr) si une future langue (LANG_PT_BR)
    // est ajoutee a l'enum sans que sa ligne du tableau soit completee.
    s = g_strings[LANG_FR][id].s;
    return s ? s : "";
}

Lang GetLanguage() {
    return g_currentLang;
}

void SetLanguage(Lang lang) {
    if (lang < 0 || lang >= LANG_COUNT)
        return;
    g_currentLang = lang;
}

void LoadLanguagePref() {
    std::ifstream f(kLangPrefPath, std::ios::binary);
    if (!f.is_open()) {
        g_currentLang = LANG_EN;   // defaut EN depuis le 2026-09-13
        return;
    }
    char c = 0;
    f.get(c);
    // "2" = LANG_PT_BR ajoute le 2026-08-24, meme convention un-octet que
    // "0"/"1". Voir X360Remap/lang.cpp (LoadPluginLanguageSetting) pour la
    // lecture cote plugin - DOIT rester synchronisee avec ce mapping.
    //
    // "0" reste explicitement le francais : c'est un choix delibere de
    // l'utilisateur. Seul le cas "contenu non reconnu / fichier vide" bascule
    // vers l'anglais depuis le 2026-09-13, comme cote plugin.
    if (c == '1')
        g_currentLang = LANG_EN;
    else if (c == '2')
        g_currentLang = LANG_PT_BR;
    else if (c == '3')
        g_currentLang = LANG_ES;   // ajoute le 2026-09-13
    else if (c == '0')
        g_currentLang = LANG_FR;
    else
        g_currentLang = LANG_EN;   // contenu non reconnu ou fichier vide
}

void SaveLanguagePref(Lang lang) {
    if (lang < 0 || lang >= LANG_COUNT)
        return;
    std::ofstream f(kLangPrefPath, std::ios::binary | std::ios::trunc);
    if (f.is_open()) {
        char c = '0';
        if (lang == LANG_EN) c = '1';
        else if (lang == LANG_PT_BR) c = '2';
        else if (lang == LANG_ES) c = '3';
        f << c;
    }
    SetLanguage(lang);
}

int CheckStringTableIntegrity() {
    // Chaque entree doit se trouver A LA POSITION de son propre identifiant.
    // Toute insertion faite au bon endroit dans l'enum mais ailleurs dans la
    // table decale un bloc entier - c'est precisement ce que cette boucle
    // attrape, la ou compter les chaines vides ne voyait rien.
    for (int lang = 0; lang < LANG_COUNT; lang++)
        for (int i = 0; i < STR_COUNT; i++)
            if ((int)g_strings[lang][i].id != i)
                return i;
    return -1;
}
